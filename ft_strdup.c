#include "libft.h"

char	*ft_strdup(const char *s)
{
	int		i;
	char	*p;

	p = malloc(ft_strlen(s) +(1 * sizeof(char)));
	i = 0;
	while (s[i] != '\0')
	{
		p[i] = s[i];
		i++;
	}
	p[i] = '\0';
	return (p);
}
